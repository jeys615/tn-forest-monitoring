import mongoose from 'mongoose';
import { env } from '../config/env.js';
import { Zone } from '../models/Zone.js';
import { SatelliteMetadata } from '../models/SatelliteMetadata.js';
import { BaselineModel } from '../models/Baseline.js';
import { MonitoringJobModel } from '../models/MonitoringJob.js';
import { IncrementalMonitoringRecordModel } from '../models/IncrementalMonitoringRecord.js';
import { ProcessedImageResultModel } from '../models/ProcessedImageResult.js';
import { AlertModel } from '../models/Alert.js';
import { User } from '../models/User.js';

/**
 * Removes invalid/fake satellite metadata records generated by the deterministic fallback,
 * cleans associated baselines and monitoring records for affected zones,
 * and preserves all user accounts.
 */
async function cleanInvalidBaselines(): Promise<void> {
  console.log('\n================================================================');
  console.log('🧹 CLEAN INVALID BASELINES & FAKE SATELLITE RECORDS');
  console.log('================================================================\n');

  await mongoose.connect(env.MONGODB_URI);
  console.log(`✅ Connected to MongoDB: ${mongoose.connection.host}/${mongoose.connection.name}\n`);

  // Phase 1: Identify fake satellite metadata records
  console.log('--- PHASE 1: IDENTIFYING FAKE SATELLITE METADATA ---');
  const allSatelliteMeta = await SatelliteMetadata.find({}).lean();
  const fakeRecords: string[] = [];

  for (const meta of allSatelliteMeta) {
    const imageId = (meta as any).imageId || (meta as any).geeImageId || '';
    const acquisitionDate = (meta as any).acquisitionDate ? new Date((meta as any).acquisitionDate) : null;
    let isFake = false;
    const reasons: string[] = [];

    // Check for deterministic tile code T44PMT (hardcoded in fake generator)
    if (imageId.includes('T44PMT')) {
      isFake = true;
      reasons.push('Contains deterministic tile code T44PMT');
    }

    // Check for pre-satellite dates (before Landsat-8 launch: 2013-02-11)
    if (acquisitionDate && acquisitionDate < new Date('2013-02-11')) {
      isFake = true;
      reasons.push(`Acquisition date ${acquisitionDate.toISOString().slice(0, 10)} is before any supported satellite`);
    }

    // Check for deterministic WRS path/row pattern
    if (imageId.includes('_144053_')) {
      isFake = true;
      reasons.push('Contains deterministic WRS path/row 144053');
    }

    if (isFake) {
      fakeRecords.push((meta as any)._id.toString());
      console.log(`  🚩 FAKE: ${imageId}`);
      reasons.forEach(r => console.log(`     Reason: ${r}`));
    }
  }

  console.log(`\n  Found ${fakeRecords.length} fake satellite metadata records out of ${allSatelliteMeta.length} total.\n`);

  // Phase 2: Clean fake satellite metadata
  if (fakeRecords.length > 0) {
    console.log('--- PHASE 2: REMOVING FAKE SATELLITE METADATA ---');
    const result = await SatelliteMetadata.deleteMany({ _id: { $in: fakeRecords } });
    console.log(`  🗑️ Deleted ${result.deletedCount} fake satellite metadata records.\n`);
  }

  // Phase 3: Clean baselines referencing fake satellite data
  console.log('--- PHASE 3: CLEANING INVALID BASELINES ---');
  const allBaselines = await BaselineModel.find({}).lean();
  const invalidBaselineIds: string[] = [];

  for (const bl of allBaselines) {
    const satelliteMetaId = (bl as any).satelliteMetadataId?.toString();
    if (satelliteMetaId && fakeRecords.includes(satelliteMetaId)) {
      invalidBaselineIds.push((bl as any)._id.toString());
      console.log(`  🚩 Invalid baseline: ${(bl as any)._id} (references fake satellite metadata ${satelliteMetaId})`);
    }
  }

  if (invalidBaselineIds.length > 0) {
    const result = await BaselineModel.deleteMany({ _id: { $in: invalidBaselineIds } });
    console.log(`  🗑️ Deleted ${result.deletedCount} invalid baseline records.\n`);
  } else {
    console.log('  ✅ No invalid baselines found.\n');
  }

  // Phase 4: Clean zone ZONE-260829-8997 specific data
  console.log('--- PHASE 4: CLEANING ZONE-260829-8997 DATA ---');
  const targetZone = await Zone.findOne({ zoneId: 'ZONE-260829-8997' });
  if (targetZone) {
    const zoneObjectId = targetZone._id.toString();
    console.log(`  Found zone: ${targetZone.name} (${targetZone.zoneId})`);

    // Clean associated satellite metadata
    const satResult = await SatelliteMetadata.deleteMany({ zoneId: zoneObjectId });
    console.log(`  🗑️ Deleted ${satResult.deletedCount} satellite metadata records for zone`);

    // Clean associated baselines
    const blResult = await BaselineModel.deleteMany({ zoneId: zoneObjectId });
    console.log(`  🗑️ Deleted ${blResult.deletedCount} baseline records for zone`);

    // Clean associated monitoring jobs
    const mjResult = await MonitoringJobModel.deleteMany({ zoneId: zoneObjectId });
    console.log(`  🗑️ Deleted ${mjResult.deletedCount} monitoring jobs for zone`);

    // Clean associated alerts
    const alResult = await AlertModel.deleteMany({ zoneId: zoneObjectId });
    console.log(`  🗑️ Deleted ${alResult.deletedCount} alerts for zone`);

    // Reset the zone's baselineDate if it's invalid (before 2013)
    if (targetZone.baselineDate && targetZone.baselineDate < new Date('2013-02-11')) {
      console.log(`  ⚠️ Zone has invalid baselineDate: ${targetZone.baselineDate.toISOString().slice(0, 10)}`);
      await Zone.updateOne({ _id: targetZone._id }, { $unset: { baselineDate: 1 } });
      console.log('  ✅ Reset zone baselineDate to null');
    }
  } else {
    console.log('  ℹ️ Zone ZONE-260829-8997 not found (may already be cleaned).');
  }

  // Phase 5: Verify user preservation
  console.log('\n--- PHASE 5: VERIFYING USER PRESERVATION ---');
  const userCount = await User.countDocuments();
  console.log(`  ✅ User accounts preserved: ${userCount}`);

  // Phase 6: Final state summary
  console.log('\n--- PHASE 6: FINAL DATABASE STATE ---');
  const finalCounts = {
    zones: await Zone.countDocuments(),
    satelliteMetadata: await SatelliteMetadata.countDocuments(),
    baselines: await BaselineModel.countDocuments(),
    monitoringJobs: await MonitoringJobModel.countDocuments(),
    alerts: await AlertModel.countDocuments(),
    users: userCount,
  };

  for (const [name, count] of Object.entries(finalCounts)) {
    const label = name === 'users' ? `${count} [PRESERVED]` : `${count}`;
    console.log(`  • ${name.padEnd(24)} : ${label}`);
  }

  console.log('\n================================================================');
  console.log('🎉 INVALID BASELINE CLEANUP COMPLETE');
  console.log('================================================================\n');
}

// Run directly if invoked as main script
const isMainScript = process.argv[1] && (
  process.argv[1].endsWith('cleanInvalidBaselines.ts') ||
  process.argv[1].endsWith('cleanInvalidBaselines.js')
);

if (isMainScript) {
  cleanInvalidBaselines()
    .then(async () => {
      await mongoose.disconnect();
      process.exitCode = 0;
    })
    .catch(async (err) => {
      console.error('❌ cleanInvalidBaselines failed:', err);
      await mongoose.disconnect();
      process.exitCode = 1;
    });
}
